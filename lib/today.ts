// ============================================================================
// 오늘 날짜 — 프롬프트에 넣을 한 줄.
// ----------------------------------------------------------------------------
// 모델은 자기가 언제인지 모른다. 안 알려주면 학습 시점을 "지금"으로 알고, 올해 뉴스의
// 날짜를 제 기억 속 연도로 바꿔 쓴다(2026년 10월 기사를 2025년 9월로 고쳐 쓴 사고).
// 본문을 다시 쓰는 호출에는 반드시 이 줄을 넣는다.
// ============================================================================

export function todayISO(): string {
  const d = new Date();
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(
    d.getDate()
  ).padStart(2, "0")}`;
}

// 날짜를 알려주고, 모르는 것을 지어내지 못하게 못을 박는 한 줄.
export function todayGuard(): string {
  return (
    `오늘은 ${todayISO()} 다. 네 지식은 오늘보다 오래됐다 — 네가 아는 "최근"을 지금으로 착각하지 마라. ` +
    "원문에 있는 날짜·수치·이름·회사명은 그대로 옮긴다. 원문에 없는 날짜나 연도를 만들어 넣지 마라. " +
    "원문 날짜가 네 기억과 어긋나도 원문을 따른다."
  );
}
